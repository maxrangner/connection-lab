// Makes the two voice clips of the call: one second each, synthesised (not recorded) and encoded as G.711 µ-law.
// Usage: node scripts/make-voice-clip.mjs
// Writes src/sim/scenarios/voiceClip.ts. Everything here is deterministic: the same bytes come out every time.
import fs from 'node:fs';

const RATE = 8000; // samples per second: the telephone rate G.711 is made for
const SECONDS = 1;
const SAMPLES = RATE * SECONDS; // 8000 samples = 50 packets of 160 (20 ms each)
const PEAK = 18000; // of 32767: loud, with headroom

/**
 * A spoken-rhythm melody: each note is a buzzy tone (a fundamental with a few harmonics, like a voice) that glides
 * from one pitch to another, with a soft attack and release. Times in seconds, pitches in Hz.
 */
function synth(notes) {
  const pcm = new Int16Array(SAMPLES);
  for (const n of notes) {
    const i0 = Math.round(n.from * RATE);
    const i1 = Math.round(n.to * RATE);
    const attack = Math.round(0.015 * RATE);
    const release = Math.round(0.04 * RATE);
    let phase = 0;
    for (let i = i0; i < i1 && i < SAMPLES; i++) {
      const k = (i - i0) / (i1 - i0);
      const f = n.f0 + (n.f1 - n.f0) * k;
      phase += (2 * Math.PI * f) / RATE;
      // Harmonics 1..4 fading out, as a vowel roughly does.
      const tone = Math.sin(phase) + 0.5 * Math.sin(2 * phase) + 0.3 * Math.sin(3 * phase) + 0.15 * Math.sin(4 * phase);
      const env = Math.min(1, (i - i0) / attack, (i1 - i) / release);
      pcm[i] = Math.round((PEAK / 1.95) * n.gain * env * tone);
    }
  }
  return pcm;
}

/** G.711 µ-law encoder (ITU-T G.711, as in Sun's g711.c): sign, 3-bit segment, 4-bit mantissa, all bits inverted. */
function ulawEncode(sample) {
  const BIAS = 0x84;
  const CLIP = 32635;
  let s = sample;
  const sign = s < 0 ? 0x80 : 0;
  if (sign) s = -s;
  if (s > CLIP) s = CLIP;
  s += BIAS;
  let exponent = 7;
  for (let mask = 0x4000; (s & mask) === 0 && exponent > 0; exponent--, mask >>= 1);
  const mantissa = (s >> (exponent + 3)) & 0x0f;
  return ~(sign | (exponent << 4) | mantissa) & 0xff;
}

const CALLER = [
  // "hel-lo": two syllables, the second falling, then quiet.
  { from: 0.06, to: 0.3, f0: 185, f1: 205, gain: 0.9 },
  { from: 0.34, to: 0.72, f0: 170, f1: 125, gain: 1 },
];
const FRIEND = [
  // "hi there": a rising "hi", then two short syllables falling away.
  { from: 0.05, to: 0.27, f0: 225, f1: 260, gain: 1 },
  { from: 0.32, to: 0.5, f0: 210, f1: 200, gain: 0.85 },
  { from: 0.53, to: 0.86, f0: 195, f1: 150, gain: 0.9 },
];

const encode = (pcm) => Buffer.from(Uint8Array.from(pcm, ulawEncode));
const caller = encode(synth(CALLER));
const friend = encode(synth(FRIEND));
if (caller.length !== SAMPLES || friend.length !== SAMPLES) throw new Error('clip length');

const describe = (notes) => notes.map((n) => `${n.from}–${n.to} s ${Math.round(n.f0)}→${Math.round(n.f1)} Hz`).join(', ');
const ts = `// AUTO-GENERATED by scripts/make-voice-clip.mjs — do not edit by hand.
// Two one-second voice clips as G.711 µ-law bytes (8000 samples at 8 kHz, one byte each): 50 RTP packets of 160 bytes.
// They are synthesised, not recorded: a spoken-rhythm melody of buzzy tones with a soft envelope, encoded with the real
// µ-law formula (segment and mantissa, bias 0x84, clip 32635). Decode with ulawDecode in src/sim/bytes/ulaw.ts.
// Caller says "hel-lo": ${describe(CALLER)}.
// Friend says "hi there": ${describe(FRIEND)}.

export const VOICE_SAMPLE_RATE = ${RATE};
export const VOICE_CLIP_SAMPLES = ${SAMPLES};

/** The caller's clip, base64 of ${caller.length} µ-law bytes. */
export const VOICE_CLIP_CALLER_BASE64 = ${JSON.stringify(caller.toString('base64'))};

/** The friend's clip, base64 of ${friend.length} µ-law bytes. */
export const VOICE_CLIP_FRIEND_BASE64 = ${JSON.stringify(friend.toString('base64'))};
`;
fs.writeFileSync('src/sim/scenarios/voiceClip.ts', ts);
console.log(`wrote ${caller.length} + ${friend.length} µ-law bytes to src/sim/scenarios/voiceClip.ts`);
