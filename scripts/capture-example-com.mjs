// Captures the exact bytes example.com sends for the request our simulated browser makes.
// Usage: node scripts/capture-example-com.mjs
// Writes tests/fixtures/example-com-response.http (raw bytes) and
// src/sim/scenarios/exampleComCapture.ts (same bytes as a TS module the sim imports).
import net from 'node:net';
import dns from 'node:dns/promises';
import fs from 'node:fs';

const REQUEST =
  'GET / HTTP/1.1\r\n' +
  'Host: example.com\r\n' +
  'User-Agent: Mozilla/5.0 (X11; Linux x86_64; rv:144.0) Gecko/20100101 Firefox/144.0\r\n' +
  'Accept: text/html\r\n' +
  'Connection: close\r\n' +
  '\r\n';

const addrs = await dns.resolve4('example.com', { ttl: true });
const ip = addrs[0].address;
const chunks = [];
await new Promise((resolve, reject) => {
  const s = net.connect(80, ip, () => s.write(REQUEST));
  s.on('data', (c) => chunks.push(c));
  s.on('end', resolve);
  s.on('error', reject);
});
const bytes = Buffer.concat(chunks);
fs.writeFileSync('tests/fixtures/example-com-response.http', bytes);
fs.writeFileSync('tests/fixtures/example-com-request.http', REQUEST);

const nonAscii = [...bytes].some((b) => b > 0x7e && b !== 0x0d && b !== 0x0a);
const ts = `// AUTO-GENERATED by scripts/capture-example-com.mjs — do not edit by hand.
// Real bytes captured from http://${ip}/ (example.com) on ${new Date().toISOString()}.
// DNS at capture time: ${addrs.map((a) => `${a.address} (TTL ${a.ttl})`).join(', ')}.

export const CAPTURED_AT = ${JSON.stringify(new Date().toISOString())};
export const CAPTURED_FROM_IP = ${JSON.stringify(ip)};
export const CAPTURED_A_RECORDS: readonly string[] = ${JSON.stringify(addrs.map((a) => a.address))};
export const CAPTURED_DNS_TTL = ${addrs[0].ttl};

/** The exact request the simulated browser sends. */
export const HTTP_REQUEST = ${JSON.stringify(REQUEST)};

/** The exact response bytes, base64-encoded (${bytes.length} bytes). */
export const HTTP_RESPONSE_BASE64 = ${JSON.stringify(bytes.toString('base64'))};
`;
fs.writeFileSync('src/sim/scenarios/exampleComCapture.ts', ts);
console.log(`captured ${bytes.length} bytes from ${ip}; non-ascii=${nonAscii}`);
console.log(bytes.toString('latin1').split('\r\n\r\n')[0]);
