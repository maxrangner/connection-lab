// Captures the exact bytes info.cern.ch sends for the first web page ever, as our simulated browser asks for it.
// Usage: node scripts/capture-info-cern.mjs
// Writes tests/fixtures/info-cern-response.http (raw bytes) and
// src/sim/scenarios/infoCernCapture.ts (same bytes as a TS module the sim imports).
import net from 'node:net';
import dns from 'node:dns/promises';
import fs from 'node:fs';

const HOST = 'info.cern.ch';
const PATH = '/hypertext/WWW/TheProject.html';
const REQUEST =
  `GET ${PATH} HTTP/1.1\r\n` +
  `Host: ${HOST}\r\n` +
  'User-Agent: Mozilla/5.0 (X11; Linux x86_64; rv:144.0) Gecko/20100101 Firefox/144.0\r\n' +
  'Accept: text/html\r\n' +
  'Connection: close\r\n' +
  '\r\n';

const addrs = await dns.resolve4(HOST, { ttl: true });
const ip = addrs[0].address;
const chunks = [];
await new Promise((resolve, reject) => {
  const s = net.connect(80, ip, () => s.write(REQUEST));
  s.on('data', (c) => chunks.push(c));
  s.on('end', resolve);
  s.on('error', reject);
});
const bytes = Buffer.concat(chunks);
fs.writeFileSync('tests/fixtures/info-cern-response.http', bytes);
fs.writeFileSync('tests/fixtures/info-cern-request.http', REQUEST);

const at = new Date().toISOString();
const ts = `// AUTO-GENERATED by scripts/capture-info-cern.mjs — do not edit by hand.
// Real bytes captured from http://${ip}${PATH} (${HOST}, the first website) on ${at}.
// DNS at capture time: ${addrs.map((a) => `${a.address} (TTL ${a.ttl})`).join(', ')}.

export const CERN_CAPTURED_AT = ${JSON.stringify(at)};
export const CERN_HOST = ${JSON.stringify(HOST)};
export const CERN_PATH = ${JSON.stringify(PATH)};
export const CERN_IP = ${JSON.stringify(ip)};
export const CERN_A_RECORDS: readonly string[] = ${JSON.stringify(addrs.map((a) => a.address))};
export const CERN_DNS_TTL = ${addrs[0].ttl};

/** The exact request the simulated browser sends. */
export const CERN_HTTP_REQUEST = ${JSON.stringify(REQUEST)};

/** The exact response bytes, base64-encoded (${bytes.length} bytes). */
export const CERN_HTTP_RESPONSE_BASE64 = ${JSON.stringify(bytes.toString('base64'))};
`;
fs.writeFileSync('src/sim/scenarios/infoCernCapture.ts', ts);
console.log(`captured ${bytes.length} bytes from ${ip}`);
console.log(bytes.toString('latin1').split('\r\n\r\n')[0]);
