// Captures the exact bytes httpbin.org sends for its JPEG, as our simulated browser asks for it.
// Usage: node scripts/capture-photo.mjs
// Writes tests/fixtures/photo-response.http (raw bytes) and
// src/sim/scenarios/photoCapture.ts (same bytes as a TS module the sim imports).
import net from 'node:net';
import dns from 'node:dns/promises';
import fs from 'node:fs';

const HOST = 'httpbin.org';
const PATH = '/image/jpeg';
const REQUEST =
  `GET ${PATH} HTTP/1.1\r\n` +
  `Host: ${HOST}\r\n` +
  'User-Agent: Mozilla/5.0 (X11; Linux x86_64; rv:144.0) Gecko/20100101 Firefox/144.0\r\n' +
  'Accept: image/jpeg\r\n' +
  'Connection: close\r\n' +
  '\r\n';

const addrs = await dns.resolve4(HOST, { ttl: true });
const ip = addrs[0].address;
const chunks = [];
await new Promise((resolve, reject) => {
  const s = net.connect(80, ip, () => s.write(REQUEST));
  s.on('data', (c) => chunks.push(c));
  s.on('end', resolve);
  s.on('error', reject);
});
const bytes = Buffer.concat(chunks);
const head = bytes.toString('latin1').split('\r\n\r\n')[0];
if (!/^HTTP\/1\.[01] 200 /.test(head) || !/^content-type: image\/jpeg/im.test(head)) throw new Error(`not a JPEG, nothing written:\n${head}`);
fs.writeFileSync('tests/fixtures/photo-response.http', bytes);
fs.writeFileSync('tests/fixtures/photo-request.http', REQUEST);

const at = new Date().toISOString();
const ts = `// AUTO-GENERATED by scripts/capture-photo.mjs — do not edit by hand.
// Real bytes captured from http://${ip}${PATH} (${HOST}) on ${at}.
// DNS at capture time: ${addrs.map((a) => `${a.address} (TTL ${a.ttl})`).join(', ')}.

export const PHOTO_CAPTURED_AT = ${JSON.stringify(at)};
export const PHOTO_HOST = ${JSON.stringify(HOST)};
export const PHOTO_PATH = ${JSON.stringify(PATH)};
export const PHOTO_IP = ${JSON.stringify(ip)};
export const PHOTO_A_RECORDS: readonly string[] = ${JSON.stringify(addrs.map((a) => a.address))};
export const PHOTO_DNS_TTL = ${addrs[0].ttl};

/** The exact request the simulated browser sends. */
export const PHOTO_HTTP_REQUEST = ${JSON.stringify(REQUEST)};

/** The exact response bytes, base64-encoded (${bytes.length} bytes). */
export const PHOTO_HTTP_RESPONSE_BASE64 = ${JSON.stringify(bytes.toString('base64'))};
`;
fs.writeFileSync('src/sim/scenarios/photoCapture.ts', ts);
console.log(`captured ${bytes.length} bytes from ${ip}`);
console.log(head);
